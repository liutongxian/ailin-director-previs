function storedLocale(): Locale {
  if (typeof window === 'undefined') return DEFAULT_LOCALE
  const value = window.localStorage.getItem(STORAGE_KEY)
  return value === 'en-US' || value === 'zh-CN' ? value : DEFAULT_LOCALE
}

let locale: Locale = storedLocale()
const listeners = new Set<() => void>()

export function getLocale(): Locale {
  return locale
}

export function setLocale(next: Locale): void {
  if (locale === next) return
  locale = next
  if (typeof window !== 'undefined') window.localStorage.setItem(STORAGE_KEY, next)
  for (const listener of listeners) listener()
}

export function translate(
  targetLocale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {}
): string {
  let text = (targetLocale === 'zh-CN' ? ZH : EN)[key] ?? EN[key]
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

export function useI18n(): {
  locale: Locale
  setLocale: typeof setLocale
  t: (key: TranslationKey, values?: Record<string, string | number>) => string
} {
  const current = useSyncExternalStore(subscribe, getLocale, () => DEFAULT_LOCALE)
  return {
    locale: current,
    setLocale,
    t: (key, values) => translate(current, key, values)
  }
}
